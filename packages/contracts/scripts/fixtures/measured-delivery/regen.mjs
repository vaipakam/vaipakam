#!/usr/bin/env node
/**
 * Regenerates ast.json, the compiler output the measured-delivery check's tests
 * read, from the .sol files beside it. The check reads solc's AST, so its
 * tests must too: a hand-written AST would test the check against the author's
 * idea of solc rather than solc.
 *
 *   node packages/contracts/scripts/fixtures/measured-delivery/regen.mjs <path-to-solc-0.8.29>
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const solc = process.argv[2];
if (!solc) throw new Error('usage: regen.mjs <path-to-solc>');
const files = ['lib/IERC20.sol', 'lib/IERC721.sol', 'lib/SafeERC20.sol', 'src/libraries/LibDelivery.sol', 'src/Raw.sol'];
const input = {
  language: 'Solidity',
  sources: Object.fromEntries(files.map((f) => [f, { content: readFileSync(join(HERE, f), 'utf8') }])),
  settings: { outputSelection: { '*': { '': ['ast'] } } },
};
const out = JSON.parse(execFileSync(solc, ['--standard-json'], { input: JSON.stringify(input) }));
const errors = (out.errors ?? []).filter((e) => e.severity === 'error');
if (errors.length) throw new Error(errors.map((e) => e.formattedMessage).join('\n'));
const version = execFileSync(solc, ['--version']).toString().match(/Version: (\S+)/)?.[1];
writeFileSync(
  join(HERE, 'ast.json'),
  `${JSON.stringify({ _readme: 'GENERATED by regen.mjs from the .sol files beside it — do not edit by hand.', solc: version, units: Object.fromEntries(files.map((f) => [f, out.sources[f].ast])) })}\n`,
);
