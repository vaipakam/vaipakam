#!/usr/bin/env node
/**
 * Regenerates ast.json, the PARSER output (stopAfter: parsing) the review
 * coverage tool's tests read, from the .sol files beside it. The tool reads
 * solc's parse tree, so its tests must too.
 *
 *   node packages/contracts/scripts/fixtures/review-coverage/regen.mjs <path-to-solc-0.8.29>
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const solc = process.argv[2];
if (!solc) throw new Error('usage: regen.mjs <path-to-solc>');
const files = ['src/Original.sol', 'src/Moved.sol', 'src/Edited.sol', 'src/Commented.sol', 'src/Iface.sol'];
const input = {
  language: 'Solidity',
  sources: Object.fromEntries(files.map((f) => [f, { content: readFileSync(join(HERE, f), 'utf8') }])),
  settings: { stopAfter: 'parsing', outputSelection: { '*': { '': ['ast'] } } },
};
const out = JSON.parse(execFileSync(solc, ['--standard-json'], { input: JSON.stringify(input) }));
const errors = (out.errors ?? []).filter((e) => e.severity === 'error');
if (errors.length) throw new Error(errors.map((e) => e.formattedMessage).join('\n'));
const version = execFileSync(solc, ['--version']).toString().match(/Version: (\S+)/)?.[1];
writeFileSync(
  join(HERE, 'ast.json'),
  `${JSON.stringify({ _readme: 'GENERATED by regen.mjs from the .sol files beside it — do not edit by hand.', solc: version, units: Object.fromEntries(files.map((f) => [f, out.sources[f].ast])) })}\n`,
);
