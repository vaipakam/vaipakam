-- #3836 — newest-first order for signed alert settings saves.
--
-- A settings save is signed by the wallet, and a save only a smart account's
-- contract approved (a Safe's owners can take longer than ten minutes) now
-- stays presentable for up to seven days. Each signed save is still accepted
-- once, but two different saves could then arrive out of order: a slow
-- approval landing after a newer save would undo it.
--
--   settings_issued_at — unix seconds named in the newest signed save applied
--                        to this row. The agent's upsert applies a save only
--                        when its signed time is not older than this, in the
--                        same statement as the write. NULL for a row no save
--                        has written yet (the link handshake makes rows too),
--                        which takes any save.
--
-- Additive: a nullable column the deployed agent does not read. Once the agent
-- that writes it ships, a deployment whose schema lacks it refuses settings
-- saves (503) rather than applying them unordered. user_thresholds is kept
-- across a Diamond change (diamondEpochKeep.json), and so is this column.
ALTER TABLE user_thresholds ADD COLUMN settings_issued_at INTEGER;
