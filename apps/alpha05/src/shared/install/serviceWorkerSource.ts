/**
 * ACC-11 — the service worker this build ships, written by the build from the
 * files it emitted (vite.config.ts `serviceWorkerPlugin`).
 *
 * The rule is the matrix row's: the worker keeps copies of THIS build's
 * hashed static files only, and only once the page has asked for one, so an
 * installed app opens without downloading its code again and a phone never
 * downloads chunks the reader does not visit. It never answers a page load
 * (a navigation always goes to the network, so a deploy is seen at once), and
 * never touches an RPC, Worker or any other origin's request: anything not on
 * this build's list passes straight through, uncached. A listed file is kept
 * only when the answer is the file itself: a page sent in its place (the
 * host's fallback for a file it no longer has, as during a deploy) is passed
 * on but never stored, so a reload can still fetch the real file. Storage is
 * optional: a store that fails to open, read or write is treated as a miss.
 * On activation it deletes every earlier build's store.
 */

/** Every store this app's worker writes starts with this. */
export const SHELL_CACHE_PREFIX = 'alpha05-shell-';

/** The files of a build the worker may keep: its hashed `assets/` output. The
 *  page itself (`index.html`) and anything public are never on the list. */
export function shellFiles(emitted: readonly string[]): string[] {
  return emitted
    .filter((f) => f.startsWith('assets/'))
    .map((f) => `/${f}`)
    .sort();
}

export function serviceWorkerSource(buildId: string, shell: readonly string[]): string {
  if (!/^[A-Za-z0-9._-]+$/.test(buildId)) throw new Error(`[service-worker] unusable build id: ${buildId}`);
  return `// Generated by the build (ACC-11): keeps copies of this build's hashed files only.
// Page loads, RPC and API requests are never answered or cached here.
const CACHE = ${JSON.stringify(SHELL_CACHE_PREFIX + buildId)};
const SHELL = new Set(${JSON.stringify(shell)});
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith(${JSON.stringify(SHELL_CACHE_PREFIX)}) && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || request.mode === 'navigate') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || url.search !== '' || !SHELL.has(url.pathname)) return;
  // The copy is optional: a store that cannot be opened or read is a miss,
  // and a copy that cannot be written is skipped, so storage never stops a file loading.
  event.respondWith(
    caches
      .open(CACHE)
      .then((cache) => cache.match(url.pathname))
      .catch(() => undefined)
      .then(
        (hit) =>
          hit ||
          fetch(request).then((response) => {
            const kind = (response.headers.get('content-type') || '').toLowerCase();
            if (response.ok && response.type === 'basic' && kind !== '' && !kind.startsWith('text/html')) {
              const copy = response.clone();
              caches.open(CACHE).then((cache) => cache.put(url.pathname, copy)).catch(() => undefined);
            }
            return response;
          }),
      ),
  );
});
`;
}
